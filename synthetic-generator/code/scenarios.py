def _q(status: str = "good", score: float = 0.94, coverage: float = 0.98,
       artifacts: tuple[str, ...] = ()) -> dict[str, Any]:
    """Return a generator-facing quality profile, not an observed device fact."""
    return {
        "status": status,
        "score": score,
        "coverage_ratio": coverage,
        "artifact_codes": list(artifacts),
    }


