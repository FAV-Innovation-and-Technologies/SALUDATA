PRIORITIES: Final[frozenset[str]] = frozenset({"emergency", "same_day", "prompt", "routine"})
REQUIRED_FIELDS: Final[frozenset[str]] = frozenset({
    "id", "title", "family", "pattern", "history", "symptoms", "interpretation",
    "alternative", "action", "uncertainty", "priority", "target_overrides",
    "quality_profile", "reasoning",
})


def validate_catalogue() -> None:
    """Raise ``ValueError`` if a hand-edited template violates catalogue invariants."""
    ids = [entry["id"] for entry in SCENARIOS]
    if len(ids) != len(set(ids)):
        raise ValueError("Scenario ids must be unique")
    for entry in SCENARIOS:
        absent = REQUIRED_FIELDS.difference(entry)
        if absent:
            raise ValueError(f"{entry.get('id', '<unknown>')}: missing {sorted(absent)}")
        if entry["priority"] not in PRIORITIES:
            raise ValueError(f"{entry['id']}: unknown priority {entry['priority']!r}")
        quality = entry["quality_profile"]
        if quality["status"] not in {"good", "usable", "poor", "unknown"}:
            raise ValueError(f"{entry['id']}: invalid quality status")
        if not 0 <= quality["score"] <= 1 or not 0 <= quality["coverage_ratio"] <= 1:
            raise ValueError(f"{entry['id']}: quality score/coverage must be in [0, 1]")
        if not isinstance(entry["symptoms"], dict) or not isinstance(entry["target_overrides"], dict):
            raise ValueError(f"{entry['id']}: symptoms and target_overrides must be mappings")
        if not all(isinstance(value, (int, float)) for value in entry["target_overrides"].values()):
            raise ValueError(f"{entry['id']}: target overrides must be numeric")


SCENARIO_COUNTS: Final[dict[str, int]] = dict(Counter(entry["family"] for entry in SCENARIOS))
validate_catalogue()
