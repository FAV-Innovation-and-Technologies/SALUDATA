"""English, synthetic scenario reference catalogue for the 2026 release.

These are *author-authored counterfactual templates*, not observations, patient
records, diagnostic labels, clinical decision rules, or a complete list of
clinical presentations.  The generator must create fresh synthetic values,
timestamps and identifiers; it must never copy source trajectories or attach a
scenario id/priority to a model input.  ``interpretation`` is deliberately
cautious and is intended only as an optional, separately-held SFT reference.

``target_overrides`` contains approximate numeric generation targets.  Scaling,
temporal smoothing, source provenance, calibration, schema selection and
quality serialization belong to the caller.  Values absent from an override
remain under the caller's baseline model.  ``weight_delta_kg`` and body-
composition deltas are relative to that synthetic person's established
baseline, rather than an assertion about a real person.
"""

